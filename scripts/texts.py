"""Проверка лимита слов: прогонять после КАЖДОЙ правки сценария, до озвучки.

python texts.py
Словом считается всё, где есть буква или цифра; тире и знаки препинания не считаются.
"""
import re

LIMIT = 60
BLOCKS = [
    ("Крючок", "У каждого горожанина есть невидимый поводок, и длину ему отмерил город."),
    ("Факт", "Королевское общество здравоохранения Британии выяснило: каждый пятый выходит из дома реже, "
             "чем хочет, — боится не найти туалет."),
    ("Поворот", "Мы меряем город километрами и станциями метро, а у двоих из пяти больных он кончается "
                "у ближайшей уборной."),
    ("Панчлайн", "Генплан без туалетов — это карта с поводком: отправь тому, кто рисует ваш город."),
]


def words(text):
    return len([x for x in text.split() if re.search(r"\w", x)])


total = 0
for name, text in BLOCKS:
    total += words(text)
    print(f"{name:<9} {words(text):>3}")
print(f"{'всего':<9} {total:>3} / {LIMIT}", "OK" if total <= LIMIT else "ПЕРЕБОР — сократить")
