@dataclass(frozen=True)
class Beat:
    """Роль блока в формате: сколько таких блоков, слов и секунд, зачем он и чем его показать."""
    role: str
    words: tuple[int, int]            # бюджет слов диктора на блок (мин, макс)
    seconds: tuple[float, float]      # ориентир по длительности блока
    goal: str
    shots: tuple[str, ...]            # подходящие шаблоны сцен, по убыванию уместности
    count: tuple[int, int] = (1, 1)   # сколько таких блоков подряд (мин, макс)


@dataclass(frozen=True)
class HookPattern:
    name: str
    title: str
    template: str
    example: str


@dataclass(frozen=True)
class Format:
    name: str                         # латиницей: --format question
    title: str                        # как называют в редакции
    when: str                         # когда брать
    beats: tuple[Beat, ...]           # тело ролика после крючка (крючок — первый Beat с role="hook")
    hooks: tuple[str, ...]            # подходящие крючки из HOOKS
    cta: tuple[str, ...]              # подходящие призывы из CTA
    loop: str                         # как закольцевать конец с началом
    seconds: tuple[int, int] = (20, 35)
    example: dict = field(default_factory=dict)

    @property
    def hook(self) -> Beat:
        return self.beats[0]

    @property
    def body(self) -> tuple[Beat, ...]:
        """Роли после крючка: их порядок общий для всех A/B-крючков."""
        return self.beats[1:]

    def beat(self, role: str) -> Beat | None:
        if role == "alt-hook":
            role = "hook"
        return next((b for b in self.beats if b.role == role), None)


