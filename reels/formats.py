def get(name: str) -> Format:
    """Формат по имени (латиницей или по-русски). KeyError с перечнем — нет такого."""
    key = str(name).strip().lower()
    key = ALIASES.get(key, key)
    if key not in FORMATS:
        raise KeyError(f"нет формата «{name}». Есть: {', '.join(FORMATS)}")
    return FORMATS[key]


def body_blocks(fmt: Format) -> tuple[int, int]:
    """Сколько блоков тела (без крючков) допускает формат: (мин, макс)."""
    return sum(b.count[0] for b in fmt.body), sum(b.count[1] for b in fmt.body)


def available_shots(beat: Beat, registry=None) -> list[str]:
    """Шаблоны из плана кадров роли, которые есть в библиотеке сцен сейчас (шаблоны добавляются по ходу)."""
    if registry is None:
        from .scenes import REGISTRY as registry
    found = [s for s in beat.shots if s in registry]
    return found or [s for s in ("headline", "stat", "list") if s in registry]


def _range(x: tuple) -> str:
    a, b = x
    fa, fb = (f"{v:g}" for v in (a, b))
    return fa if a == b else f"{fa}–{fb}"


def describe(names=None, registry=None) -> str:
    """Библиотека форматов в Markdown: для запроса к LLM и для людей (docs/scripting.md)."""
    out = []
    for f in (FORMATS[n] for n in (names or FORMATS)):
        lines = [f"### {f.name} — {f.title}", "", f"Когда: {f.when}", f"Длина: {_range(f.seconds)} с.", "",
                 "| роль | блоков | слов | секунд | задача | кадры |", "|---|---|---|---|---|---|"]
        for b in f.beats:
            shots = ", ".join(available_shots(b, registry))
            lines.append(f"| {b.role} | {_range(b.count)} | {_range(b.words)} | {_range(b.seconds)} | {b.goal} | "
                         f"{shots} |")
        lines += ["", "Крючки: " + "; ".join(f"{HOOKS[h].title} («{HOOKS[h].example}»)" for h in f.hooks),
                  "Призыв: " + "; ".join(f"{CTA[c][0]} («{CTA[c][1]}»)" for c in f.cta),
                  f"Закольцовка: {f.loop}", ""]
        out.append("\n".join(lines))
    return "\n".join(out).rstrip() + "\n"


def describe_hooks() -> str:
    return "\n".join(f"- **{h.title}** (`{h.name}`): {h.template} Пример: «{h.example}»" for h in HOOKS.values()) + "\n"


